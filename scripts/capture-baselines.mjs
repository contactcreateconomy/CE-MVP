#!/usr/bin/env node
/**
 * capture-baselines (R3) — 16 core routes × {390, 1440} × {logged-out, logged-in}
 * → ak-redesign/00-control/baselines/ + labelled contact sheets.
 *
 * Prereqs: `pnpm backend` + `pnpm dev` running; `pnpm reset:local` executed
 * (captures live demo data; logged-in = devtest@example.com).
 *
 * Notes carried from R2: no --wait-until=networkidle (Convex websockets keep
 * a connection open, so it never fires); the Next dev-tools badge and the
 * cookie banner are hidden/dismissed before capture.
 */
import { chromium } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const BASE = "http://localhost:3000";
const OUT_DIR = path.resolve("ak-redesign/00-control/baselines");
mkdirSync(OUT_DIR, { recursive: true });

const browser0 = await chromium.launch(
  // system browsers: the Playwright CDN download failed on this network —
  // Edge/Chrome channels are the same engine with zero download.
  process.env.PW_CHANNEL ? { channel: process.env.PW_CHANNEL } : { channel: "msedge" },
);
{
  // post ids (and therefore slugs) are regenerated by every reset:local —
  // discover the live thread slug from the feed instead of hardcoding
  const p = await browser0.newPage();
  await p.goto(`${BASE}/feed`, { waitUntil: "domcontentloaded" });
  await p.waitForTimeout(2500);
  const slug = await p.evaluate(() => {
    const a = document.querySelector('a[href^="/discussions/"]');
    return a ? a.getAttribute("href") : null;
  });
  await p.close();
  if (!slug) throw new Error("no /discussions/ link found on the feed — did reset:local + seed:demo run?");
  globalThis.__threadSlug = slug.replace("/discussions/", "");
}
await browser0.close();
const THREAD_SLUG = globalThis.__threadSlug;
console.log(`thread slug: ${THREAD_SLUG}`);

// RAW-INVENTORY section E — the 16 core routes.
const ROUTES = [
  { name: "landing", path: "/landing" },
  { name: "signin", path: "/signin" },
  { name: "welcome", path: "/welcome" }, // 307 → /feed
  { name: "setup", path: "/setup" },
  { name: "feed", path: "/feed" },
  { name: "discussion", path: `/discussions/${THREAD_SLUG}` },
  { name: "new-post", path: "/new-post" },
  { name: "user", path: "/users/maya" },
  { name: "profile", path: "/profile" }, // redirect → /settings/profile
  { name: "notifications", path: "/notifications" },
  { name: "search", path: "/search" },
  { name: "discover", path: "/discover" },
  { name: "category", path: "/category/debate" },
  { name: "leaderboard", path: "/leaderboard" },
  { name: "drafts", path: "/drafts" },
  { name: "settings", path: "/settings" }, // redirect → /settings/profile
];

const VIEWPORTS = [
  { name: "390", width: 390, height: 844 },
  { name: "1440", width: 1440, height: 900 },
];

async function dismissChrome(page) {
  // cookie consent banner (if present) — backup for the context init script
  const btn = page.getByRole("button", { name: /^(Save choices|Essentials only)$/ });
  if ((await btn.count()) > 0) {
    await btn.first().click({ timeout: 2000 }).catch(() => {});
  }
  // Next dev-tools badge + dialogs
  await page.addStyleTag({
    content: `nextjs-portal, [data-nextjs-dev-tools-button], [data-next-badge] { display: none !important; }`,
  }).catch(() => {});
}

// the CMP banner's dismissal flag lives in sessionStorage (per tab) — set it
// before any page script runs so no capture ever shows the overlay
const noConsentBanner = () => sessionStorage.setItem("cmp.dismissed", "1");

async function login(page) {
  await page.goto(`${BASE}/feed`, { waitUntil: "domcontentloaded" });
  await page.waitForTimeout(1500);
  await page.getByRole("button", { name: "Login" }).first().click();
  const dialog = page.getByRole("dialog");
  await dialog.waitFor({ state: "visible", timeout: 5000 });
  await dialog.getByRole("textbox", { name: "Email" }).fill("devtest@example.com");
  await dialog.getByRole("textbox", { name: "Password" }).fill("DevTest2026!");
  await dialog.getByRole("button", { name: "Sign in" }).click();
  await page.waitForTimeout(4000); // session + profile settle
}

async function capture(context, route, viewport, stateLabel) {
  const page = await context.newPage();
  await page.setViewportSize({ width: viewport.width, height: viewport.height });
  await page.goto(`${BASE}${route.path}`, { waitUntil: "domcontentloaded" });
  await page.waitForTimeout(2500); // Convex subscribe + render settle
  await dismissChrome(page);
  await page.waitForTimeout(400);
  const file = path.join(OUT_DIR, `${route.name}-${viewport.name}-${stateLabel}.png`);
  await page.screenshot({ path: file, fullPage: true });
  await page.close();
  console.log(`  [✓] ${path.basename(file)}`);
}

const browser = await chromium.launch(
  process.env.PW_CHANNEL ? { channel: process.env.PW_CHANNEL } : { channel: "msedge" },
);
try {
  const sheetsOnly = process.argv.includes("--sheets-only");
  if (!sheetsOnly) {
  for (const viewport of VIEWPORTS) {
    // logged-out pass (fresh context)
    const out = await browser.newContext();
    await out.addInitScript(noConsentBanner);
    for (const route of ROUTES) await capture(out, route, viewport, "out");
    await out.close();

    // logged-in pass (one login per context)
    const inn = await browser.newContext();
    await inn.addInitScript(noConsentBanner);
    const loginPage = await inn.newPage();
    await loginPage.setViewportSize({ width: viewport.width, height: viewport.height });
    await login(loginPage);
    await loginPage.close();
    for (const route of ROUTES) await capture(inn, route, viewport, "in");
    await inn.close();
  }
  }

  // ── contact sheets: labelled grids via a rendered HTML page ─────────
  // 4 columns (two routes per row, out+in each), cells height-capped so
  // the sheet stays readable — full-length pages are in the individual
  // PNGs next to this sheet.
  for (const viewport of VIEWPORTS) {
    const cells = [];
    for (const route of ROUTES) {
      for (const stateLabel of ["out", "in"]) {
        cells.push({ label: `${route.name} — ${stateLabel === "in" ? "logged-in" : "logged-out"} (${route.path})`, file: `${route.name}-${viewport.name}-${stateLabel}.png` });
      }
    }
    const html = `<!doctype html><html><body style="margin:0;font-family:Segoe UI,Arial,sans-serif;background:#111;color:#eee">
<div style="display:grid;grid-template-columns:repeat(4,1fr);gap:12px;padding:12px">
${cells.map((c) => `<figure style="margin:0;height:900px;overflow:hidden">
  <figcaption style="font-size:13px;padding:5px 7px;background:#222;border-radius:4px 4px 0 0">${c.label}</figcaption>
  <img src="${c.file}" style="width:100%;height:auto;display:block;border:1px solid #333"/>
</figure>`).join("\n")}
</div></body></html>`;
    const htmlPath = path.join(OUT_DIR, `.contact-${viewport.name}.html`);
    writeFileSync(htmlPath, html);
    const sheetPage = await browser.newPage({ viewport: { width: viewport.name === "390" ? 1000 : 2400, height: 900 } });
    await sheetPage.goto(`file:///${htmlPath.replace(/\\/g, "/")}`, { waitUntil: "load" });
    await sheetPage.waitForTimeout(1500);
    const sheetPath = path.join(OUT_DIR, `CONTACT-${viewport.name}.png`);
    await sheetPage.screenshot({ path: sheetPath, fullPage: true });
    await sheetPage.close();
    (await import("node:fs")).rmSync(htmlPath, { force: true });
    console.log(`  [✓] ${path.basename(sheetPath)}`);
  }
} finally {
  await browser.close();
}
console.log("\nbaselines complete — ak-redesign/00-control/baselines/");
